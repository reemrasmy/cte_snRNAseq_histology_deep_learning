def save_results(
    fold_metrics,
    all_predictions,
    fold_assignments,
    args: argparse.Namespace,
    output_dirs: dict[str, Path],
) -> None:
    results_dir = output_dirs["results"]

    metrics_df = pd.DataFrame(fold_metrics)
    predictions_df = pd.DataFrame(all_predictions)
    fold_assignments_df = pd.DataFrame(fold_assignments)

    print("\n" + "=" * 60)
    print("Overall Cross Validation Results")
    print("=" * 60)

    print(
        f"Mean Accuracy: {metrics_df['val_accuracy'].mean():.4f} ± "
        f"{metrics_df['val_accuracy'].std():.4f}"
    )
    print(
        f"Mean Macro-F1: {metrics_df['val_macro_f1'].mean():.4f} ± "
        f"{metrics_df['val_macro_f1'].std():.4f}"
    )
    print(
        f"Mean Low F1: {metrics_df['low_f1'].mean():.4f} ± "
        f"{metrics_df['low_f1'].std():.4f}"
    )
    print(
        f"Mean High F1: {metrics_df['high_f1'].mean():.4f} ± "
        f"{metrics_df['high_f1'].std():.4f}"
    )

    required = {
        "fold",
        "best_epoch",
        "donor_id",
        "slide_id",
        args.label_column,
        "true_label",
        "pred_label",
        "prob_low",
        "prob_high",
    }

    missing = required.difference(predictions_df.columns)
    if missing:
        raise ValueError(f"Prediction output is missing columns: {sorted(missing)}")

    if predictions_df["prob_high"].isna().any():
        raise ValueError("predictions.csv contains missing prob_high values.")

    if not predictions_df["prob_high"].between(0, 1).all():
        raise ValueError("predictions.csv contains prob_high values outside [0, 1].")

    if len(predictions_df) != len(fold_assignments_df):
        raise ValueError(
            "Prediction count does not match the number of held-out CV samples."
        )

    if predictions_df["slide_id"].duplicated().any():
        duplicated = predictions_df.loc[
            predictions_df["slide_id"].duplicated(keep=False),
            ["fold", "slide_id"],
        ]
        raise ValueError(
            "Some slides have more than one cross-validation prediction:\n"
            f"{duplicated}"
        )

    metrics_df.to_csv(results_dir / "fold_metrics.csv", index=False)
    predictions_df.to_csv(results_dir / "predictions.csv", index=False)
    fold_assignments_df.to_csv(results_dir / "fold_assignments.csv", index=False)

    class_names = [args.low_label, args.high_label]

    save_classification_summary(
        predictions_df=predictions_df,
        output_dir=results_dir,
        class_names=class_names,
    )

    pooled_auc = save_roc_outputs(
        predictions_df=predictions_df,
        output_dir=results_dir,
        stain=args.stain,
    )

    print("\nSaved results:")
    print(results_dir / "fold_metrics.csv")
    print(results_dir / "predictions.csv")
    print(results_dir / "fold_assignments.csv")
    print(results_dir / "confusion_matrix.png")
    print(results_dir / "classification_report.csv")
    print(results_dir / "roc_curve.png")
    print(results_dir / "roc_curve_points.csv")
    print(results_dir / "roc_auc_summary.csv")
    print(f"Pooled ROC-AUC: {pooled_auc:.4f}")


############################## Main ##############################

def main() -> None:
    args = parse_args()

    set_seed(args.seed)
    output_dirs = create_output_dirs(args)
    save_run_config(args, output_dirs["results"])

    print(f"Using device: {DEVICE}")
    print(f"Stain: {args.stain}")
    print(f"Classes: {args.low_label} = 0, {args.high_label} = 1")
    print(f"Results directory:\n{output_dirs['results']}")

    df = load_metadata(
        metadata_csv=args.metadata,
        label_column=args.label_column,
        low_label=args.low_label,
        high_label=args.high_label,
    )

    fold_metrics, all_predictions, fold_assignments = run_cross_validation(
        df,
        args,
        output_dirs,
    )

    save_results(
        fold_metrics,
        all_predictions,
        fold_assignments,
        args,
        output_dirs,
    )

    print("\nClassification modeling complete.")


if __name__ == "__main__":
    main()




