"""
ABMIL classification for Low-vs-High CTE stage prediction from UNI2 whole-slide histology embeddings.

Current implementation:
    - Supports one embedding file / WSI per donor.
    - Uses donor-grouped stratified cross-validation.
    - Selects checkpoint with highest validation Macro-F1.
    - Does not yet combine multiple embedding files or stains per donor.

Figures are generated by:
    - visualization/attention_heatmaps.py
    - visualization/high_attention_tiles.py
    - visualization/confusion_matrix.py
    - visualization/roc_curve.py

Example Run:
    python src/modeling/abmil_cte_stage_classification.py \
        --metadata /path/to/modeling_metadata.csv \
        --output-dir /path/to/results/stage_classification \
        --stain AT8 \
        --coordinate-source native \
        --target-name low_vs_high \

Run with --help to see all available options.
"""

